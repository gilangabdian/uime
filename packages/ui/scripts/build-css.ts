import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { primitives } from "../src/tokens/primitives.js";
import { semantic } from "../src/tokens/semantic.js";
import { components } from "../src/tokens/components.js";

const currentDir = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(currentDir, "../dist");
const injectFile = resolve(currentDir, "../src/tokens/inject-styles.ts");

function toKebab(input: string): string {
  return input
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/_/g, "-")
    .toLowerCase();
}

function flattenTokens(
  obj: Record<string, unknown>,
  prefix: string[] = [],
): Array<[string, string]> {
  const entries: Array<[string, string]> = [];
  for (const [key, value] of Object.entries(obj)) {
    const nextPrefix = [...prefix, toKebab(key)];
    if (value !== null && typeof value === "object") {
      entries.push(...flattenTokens(value as Record<string, unknown>, nextPrefix));
    } else if (typeof value === "string" || typeof value === "number") {
      entries.push([`--uime-${nextPrefix.join("-")}`, String(value)]);
    }
  }
  return entries;
}

function formatBlock(selector: string, vars: Array<[string, string]>): string {
  const lines = vars.map(([name, val]) => `  ${name}: ${val};`).join("\n");
  return `${selector} {\n${lines}\n}`;
}

function generateTokensCss(): string {
  const primitiveVars = flattenTokens(primitives as unknown as Record<string, unknown>);
  const darkSemanticVars = flattenTokens(semantic.dark as unknown as Record<string, unknown>);
  const lightSemanticVars = flattenTokens(semantic.light as unknown as Record<string, unknown>);
  const componentVars = flattenTokens(components as unknown as Record<string, unknown>);

  const header = [
    "/**",
    " * uime — Generated Atmospheric & Translucent Tokens",
    " * DO NOT EDIT THIS FILE DIRECTLY. Edit packages/ui/src/tokens/* and run `pnpm build`.",
    " */",
  ].join("\n");

  const rootBlock = formatBlock(':root, [data-theme="dark"]', [
    ...primitiveVars,
    ...darkSemanticVars,
    ...componentVars,
  ]);

  const lightBlock = formatBlock('[data-theme="light"]', lightSemanticVars);

  return `${header}\n\n${rootBlock}\n\n${lightBlock}\n`;
}

function generateInjectStylesTs(cssText: string): string {
  return [
    "/**",
    " * Auto-generated by scripts/build-css.ts — DO NOT EDIT MANUALLY.",
    " * Automatically injects uime CSS tokens into document.head when imported in the browser.",
    " */",
    `export const UIME_TOKENS_CSS = ${JSON.stringify(cssText)};`,
    "",
    'const STYLE_ELEMENT_ID = "uime-tokens-styles";',
    "",
    "export function ensureUimeStyles(): void {",
    '  if (typeof document === "undefined") {',
    "    return;",
    "  }",
    "  if (document.getElementById(STYLE_ELEMENT_ID)) {",
    "    return;",
    "  }",
    '  const styleEl = document.createElement("style");',
    "  styleEl.id = STYLE_ELEMENT_ID;",
    "  styleEl.textContent = UIME_TOKENS_CSS;",
    "  document.head.appendChild(styleEl);",
    "}",
    "",
  ].join("\n");
}

mkdirSync(distDir, { recursive: true });
const tokensCss = generateTokensCss();

writeFileSync(resolve(distDir, "tokens.css"), tokensCss, "utf8");
writeFileSync(resolve(distDir, "styles.css"), tokensCss, "utf8");
writeFileSync(injectFile, generateInjectStylesTs(tokensCss), "utf8");

console.log(
  "✓ Generated packages/ui/dist/tokens.css, dist/styles.css, and src/tokens/inject-styles.ts",
);
